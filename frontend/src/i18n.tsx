export type I18nKey = keyof typeof strings['en']

const Ctx = createContext<I18nState | null>(null)

function detectDefault(): Lang {
  try {
    const saved = localStorage.getItem(LS_LANG) as Lang | null
    if (saved === 'en' || saved === 'it' || saved === 'sl' || saved === 'et' || saved === 'be' || saved === 'lt' || saved === 'hr') return saved
  } catch {}
  try {
    const n = navigator.language?.toLowerCase() || ''
    if (n.startsWith('it')) return 'it'
    if (n.startsWith('sl')) return 'sl'
    if (n.startsWith('et')) return 'et'
    if (n.startsWith('lt')) return 'lt'
    if (n.startsWith('hr')) return 'hr'
    // Belgium (French/Dutch) – fallback
    if (n.startsWith('fr') || n.startsWith('nl')) return 'be'
  } catch {}
  return 'en'
}

function toHtmlLang(l: Lang) {
  switch (l) {
    case 'en':
      return 'en'
    case 'it':
      return 'it'
    case 'sl':
      return 'sl'
    case 'et':
      return 'et'
    case 'lt':
      return 'lt'
    case 'hr':
      return 'hr'
    case 'be':
      return 'fr-BE'
    default:
      return 'en'
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => detectDefault())

  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem(LS_LANG, l) } catch {}
    try { document.documentElement.setAttribute('lang', toHtmlLang(l)) } catch {}
  }

  const t = useMemo(() => {
    return (key: keyof typeof strings['en']) => strings[lang][key] || strings.en[key]
  }, [lang])

  const value: I18nState = { lang, setLang, t }
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

